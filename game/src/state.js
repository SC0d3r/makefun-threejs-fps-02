// The one mutable game object. Math helpers live in util; modules add their own
// scratch vectors at module scope and write only through this object in step().
import { mulberry32 } from './util.js';
import { WEAPONS, ECONOMY, PLAYER, MAP } from './config.js';

export function createState(seed = 1) {
  const state = {
    seed,
    rng: mulberry32(seed),
    time: 0,
    mode: 'menu',
    paused: false,
    shotMode: false,
    shotFrozen: false,
    colliders: [],
    shootables: [],
    audio: null,
    player: {
      pos: { x: MAP.attackerSpawn[0], y: 0, z: MAP.attackerSpawn[1] },
      vel: { x: 0, y: 0, z: 0 },
      yaw: 0,
      pitch: 0,
      height: PLAYER.stand,
      eye: PLAYER.eye,
      crouch: 0,
      onGround: true,
      health: 100,
      armor: 0,
      alive: true,
      money: ECONOMY.loss,
      speed: 0,
      walk: false,
      moving: false,
      deadT: 0,
      damageDir: 0,
      flash: 0,
      grenadeSelect: null,
      grenades: { frag: 0, flash: 0 },
      lastDamage: 99,
      firedAt: 99,
      stepDist: 0,
      stepSide: 0,
    },
    weapon: {
      current: 'pistol',
      primary: null,
      owned: { pistol: true, smg: false, rifle: false, shotgun: false },
      ammo: {},
      cooldown: 0,
      reloading: 0,
      spread: 0,
    },
    round: {
      number: 1,
      phase: 'menu',
      timer: 0,
      fuse: 0,
      score: [0, 0],
      result: '',
      reason: '',
      ended: 0,
      plantSite: null,
      plantProgress: 0,
      defuseProgress: 0,
      defusing: false,
      beep: 0,
      beepGap: 1,
      moneyDelta: 0,
    },
    bomb: {
      planted: false,
      x: 0,
      z: 0,
      led: 0,
    },
    stats: { kills: 0, plants: 0, shots: 0, hits: 0, rounds: 0 },
    bots: [],
    feed: [],
    flags: {
      buyOpen: false,
      startOpen: true,
      roundEnd: false,
      matchEnd: false,
      defused: false,
    },
    match: { result: '' },
    hitMarker: 0,
    damageFlash: 0,
    prompt: '',
  };
  for (const id of Object.keys(WEAPONS)) {
    state.weapon.ammo[id] = { mag: WEAPONS[id].mag, reserve: WEAPONS[id].reserve };
  }
  return state;
}
